/**
 * Manufacturing → Schedule Proposals — the persisted, VERSIONED, read-only-first governance record for a
 * routing plan. A production order proposes a schedule (mined by the routing engine, captured here inert);
 * a human drives it through a strict lifecycle — proposed → approved / rejected → committed, or superseded
 * on recalculate. Only an APPROVED proposal may commit, and commit creates the real Production Schedule
 * records (reusing that module) — so nothing persists to the shop floor without approval. Rejection needs a
 * reason; recalculate mints the next version. Every transition flows through the framework's RBAC + audit +
 * timeline. The AI explains; a human approves. Modeled on the Decision Execution Handoff governance.
 */
