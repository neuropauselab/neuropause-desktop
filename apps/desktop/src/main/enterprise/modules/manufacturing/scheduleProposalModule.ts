export function createScheduleProposalModule(storePath: string): EnterpriseModule {
  const store = new EnterpriseRecordStore(storePath, SCHEDULE_PROPOSALS_MODULE_ID, SCHEDULE_PROPOSAL_KIND);

  return defineEnterpriseModule({
    descriptor: SCHEDULE_PROPOSAL_DESCRIPTOR,
    store,
    hooks: {
      summarize: async (record): Promise<EnterpriseRecordSummary> => {
        const p = scheduleProposalFromRecord(record);
        return {
          moduleId: SCHEDULE_PROPOSALS_MODULE_ID,
          recordId: record.id,
          headline: `${p.proposalNumber} · v${p.version} · ${p.status}`,
          summary:
            `Schedule proposal for ${p.productionOrder} (${p.product}) via routing ${p.routingNumber}: ` +
            `${p.scheduledOps} scheduled, ${p.blockedOps} blocked op(s). ${p.status === 'committed' ? 'Committed to real Production Schedules.' : 'Read-only until approved — nothing runs automatically.'}`,
          risk: p.blockedOps > 0 || p.late ? 'medium' : 'low',
          riskReason: p.blockedOps > 0 ? `${p.blockedOps} blocked operation(s).` : p.late ? 'Projected to finish late.' : `Proposal ${p.status}.`,
          executiveExplanation: `${p.proposalNumber} is ${p.status}; a human approves before any Production Schedule is committed.`,
          grounded: false,
          model: 'none',
        };
      },
      runAction: async (action, record, ctx) => {
        const p = scheduleProposalFromRecord(record);
        const actor = ctx.actor() ?? '';
        const now = ctx.now();
        const emitSelf = (rec: ReturnType<typeof store.update>): void => {
          const self = ctx.moduleFor(SCHEDULE_PROPOSALS_MODULE_ID);
          if (self && rec) ctx.emit(self, 'updated', rec);
        };

        // Recalculate is not a simple self-transition — it supersedes this record and mints the next version.
        if (action === RECALCULATE_ACTION) {
          if (p.status !== 'proposed' && p.status !== 'approved') return { ok: false, message: `Cannot recalculate a ${p.status} proposal.` };
          return recalculateProposal(record, ctx);
        }

        const target = scheduleProposalTransition(action as never, p.status);
        if (!target) return { ok: false, message: `Cannot ${action} a proposal that is ${p.status}.` };

        if (action === REJECT_ACTION) {
          if (!p.rejectionReason.trim()) return { ok: false, message: 'A rejection reason is required before rejecting a schedule proposal.' };
          emitSelf(store.update(record.id, { fields: { status: 'rejected', rejectedBy: actor, rejectedAt: now }, actor, now }));
          return { ok: true, message: `Rejected ${p.proposalNumber}. Nothing was committed.` };
        }

        if (action === APPROVE_ACTION) {
          emitSelf(store.update(record.id, { fields: { status: 'approved', approvedBy: actor, approvedAt: now }, actor, now }));
          return { ok: true, message: `Approved ${p.proposalNumber} — ready to commit.` };
        }

        if (action === COMMIT_ACTION) {
          const result = await commitProposal(record, ctx);
          if (!result.ok) return result;
          const ids = (result as { createdIds?: string[] }).createdIds ?? [];
          emitSelf(store.update(record.id, { fields: { status: 'committed', committedBy: actor, committedAt: now, committedSchedules: ids.join(',') }, actor, now }));
          return { ok: true, message: `Committed ${ids.length} scheduled operation(s) from ${p.proposalNumber}.` };
        }

        return { ok: false, error: `Unknown action "${action}".` };
      },
    },
  });
}
